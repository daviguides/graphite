//! Quick tree-sitter extraction: symbols, raw calls, raw imports, raw implements.
//! Good enough to measure graph shape; not a production resolver.

use std::collections::HashMap;
use std::path::Path;
use tree_sitter::{Node, Parser};

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Fam {
    Rust,
    Py,
    Js,
    Go,
}

impl Fam {
    pub fn name(self) -> &'static str {
        match self {
            Fam::Rust => "rust",
            Fam::Py => "python",
            Fam::Js => "ts/js",
            Fam::Go => "go",
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Rust,
    Py,
    Ts,
    Tsx,
    Js,
    Go,
}

impl Lang {
    pub fn from_path(p: &str) -> Option<Lang> {
        let ext = p.rsplit('.').next()?;
        Some(match ext {
            "rs" => Lang::Rust,
            "py" => Lang::Py,
            "ts" | "mts" | "cts" => Lang::Ts,
            "tsx" => Lang::Tsx,
            "js" | "jsx" | "mjs" | "cjs" => Lang::Js,
            "go" => Lang::Go,
            _ => return None,
        })
    }
    pub fn fam(self) -> Fam {
        match self {
            Lang::Rust => Fam::Rust,
            Lang::Py => Fam::Py,
            Lang::Ts | Lang::Tsx | Lang::Js => Fam::Js,
            Lang::Go => Fam::Go,
        }
    }
}

#[derive(Clone, Debug)]
pub struct Sym {
    pub name: String,
    pub kind: &'static str,
    pub parent_type: Option<String>,
    pub file: usize,
    pub line: u32,
}

impl Sym {
    pub fn is_type(&self) -> bool {
        matches!(
            self.kind,
            "struct" | "enum" | "trait" | "class" | "interface" | "type" | "union"
        )
    }
    pub fn is_callable(&self) -> bool {
        matches!(self.kind, "function" | "method" | "class" | "struct")
    }
}

#[derive(Clone, Debug)]
pub struct RawCall {
    pub caller: usize,
    pub name: String,
    pub qualifier: Option<String>,
    pub is_self: bool,
    /// enclosing type for self-calls
    pub self_type: Option<String>,
}

#[derive(Clone, Debug)]
pub struct RawImpl {
    /// implementing symbol if known, else type name to resolve in file scope
    pub src_sym: Option<usize>,
    pub src_type: Option<String>,
    pub base: String,
    pub file: usize,
}

#[derive(Clone, Debug, Default)]
pub struct RawImports {
    /// local name -> (module spec, original name)
    pub names: Vec<(String, String, String)>,
    /// alias -> module spec (namespace / package / module import)
    pub modules: Vec<(String, String)>,
    /// module specs imported at all (for file->file import edges)
    pub specs: Vec<String>,
}

#[derive(Clone, Debug)]
pub struct FileRec {
    pub path: String,
    pub lang: Lang,
    pub module_sym: usize,
    pub imports: RawImports,
}

#[derive(Default)]
pub struct Extracted {
    pub files: Vec<FileRec>,
    pub syms: Vec<Sym>,
    pub calls: Vec<RawCall>,
    pub impls: Vec<RawImpl>,
    /// (container, member) known at extraction time
    pub contains: Vec<(usize, usize)>,
    /// (member method, type name) — container resolved later (Rust impl / Go receiver)
    pub contains_by_type: Vec<(usize, String)>,
    pub parse_errors: usize,
    pub generated_skipped: usize,
}

/// Standard generated-code markers in the file header.
fn is_generated(src: &[u8]) -> bool {
    let head = String::from_utf8_lossy(&src[..src.len().min(1024)]);
    (head.contains("Code generated") && head.contains("DO NOT EDIT"))
        || head.contains("@generated")
        || head.contains("autogenerated by")
        || head.contains("auto-generated by")
}

struct Walker<'a> {
    src: &'a [u8],
    file: usize,
    lang: Lang,
    out: &'a mut Extracted,
}

fn text<'a>(n: Node, src: &'a [u8]) -> &'a str {
    n.utf8_text(src).unwrap_or("")
}

fn last_ident(s: &str) -> String {
    let s = s.split('<').next().unwrap_or(s);
    s.rsplit(|c: char| c == ':' || c == '.')
        .next()
        .unwrap_or(s)
        .trim_start_matches('&')
        .trim_start_matches('*')
        .trim()
        .to_string()
}

impl<'a> Walker<'a> {
    fn add(&mut self, name: &str, kind: &'static str, node: Node, parent_type: Option<String>) -> usize {
        let idx = self.out.syms.len();
        self.out.syms.push(Sym {
            name: name.to_string(),
            kind,
            parent_type,
            file: self.file,
            line: node.start_position().row as u32 + 1,
        });
        idx
    }

    fn call(&mut self, caller: usize, name: String, qualifier: Option<String>, self_type: &Option<String>) {
        if name.is_empty() {
            return;
        }
        let is_self = matches!(
            qualifier.as_deref(),
            Some("self") | Some("this") | Some("cls") | Some("Self")
        );
        self.out.calls.push(RawCall {
            caller,
            name,
            qualifier: if is_self { None } else { qualifier },
            is_self,
            self_type: if is_self { self_type.clone() } else { None },
        });
    }

    /// container: symbol that structurally contains new symbols
    /// enclosing: symbol attributed as caller for call sites
    /// cur_type: enclosing class/impl/receiver type name
    fn walk(&mut self, node: Node, container: usize, enclosing: usize, cur_type: Option<String>) {
        match self.lang {
            Lang::Rust => self.rust(node, container, enclosing, cur_type),
            Lang::Py => self.py(node, container, enclosing, cur_type),
            Lang::Go => self.go(node, container, enclosing, cur_type),
            _ => self.js(node, container, enclosing, cur_type),
        }
    }

    fn children(&mut self, node: Node, container: usize, enclosing: usize, cur_type: Option<String>) {
        let mut c = node.walk();
        let kids: Vec<Node> = node.named_children(&mut c).collect();
        for k in kids {
            self.walk(k, container, enclosing, cur_type.clone());
        }
    }

    // ---------------- Rust ----------------
    fn rust(&mut self, node: Node, container: usize, enclosing: usize, cur_type: Option<String>) {
        let src = self.src;
        match node.kind() {
            "function_item" | "function_signature_item" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let kind = if cur_type.is_some() { "method" } else { "function" };
                let s = self.add(name, kind, node, cur_type.clone());
                if cur_type.is_some() && container == self.out.files[self.file].module_sym {
                    self.out.contains_by_type.push((s, cur_type.clone().unwrap()));
                } else {
                    self.out.contains.push((container, s));
                }
                if let Some(b) = node.child_by_field_name("body") {
                    self.walk(b, s, s, cur_type);
                }
            }
            "struct_item" | "enum_item" | "union_item" | "type_item" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let kind = match node.kind() {
                    "struct_item" => "struct",
                    "enum_item" => "enum",
                    "union_item" => "union",
                    _ => "type",
                };
                let s = self.add(name, kind, node, None);
                self.out.contains.push((container, s));
            }
            "trait_item" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string();
                let s = self.add(&name, "trait", node, None);
                self.out.contains.push((container, s));
                if let Some(b) = node.child_by_field_name("body") {
                    self.children(b, s, enclosing, Some(name));
                }
            }
            "impl_item" => {
                let ty = node.child_by_field_name("type").map(|n| last_ident(text(n, src))).unwrap_or_default();
                if let Some(tr) = node.child_by_field_name("trait") {
                    self.out.impls.push(RawImpl {
                        src_sym: None,
                        src_type: Some(ty.clone()),
                        base: last_ident(text(tr, src)),
                        file: self.file,
                    });
                }
                if let Some(b) = node.child_by_field_name("body") {
                    self.children(b, container, enclosing, Some(ty));
                }
            }
            "use_declaration" => {
                if let Some(arg) = node.child_by_field_name("argument") {
                    let mut names = Vec::new();
                    collect_rust_use(arg, src, &mut names);
                    let spec = text(arg, src).to_string();
                    for (local, orig) in names {
                        self.out.files[self.file].imports.names.push((local, spec.clone(), orig));
                    }
                    self.out.files[self.file].imports.specs.push(spec);
                }
            }
            "call_expression" => {
                if let Some(f) = node.child_by_field_name("function") {
                    let (name, qual) = rust_callee(f, src);
                    self.call(enclosing, name, qual, &cur_type);
                }
                self.children(node, container, enclosing, cur_type);
            }
            "struct_expression" => {
                if let Some(n) = node.child_by_field_name("name") {
                    self.call(enclosing, last_ident(text(n, src)), None, &cur_type);
                }
                self.children(node, container, enclosing, cur_type);
            }
            "macro_invocation" => {}
            _ => self.children(node, container, enclosing, cur_type),
        }
    }

    // ---------------- Python ----------------
    fn py(&mut self, node: Node, container: usize, enclosing: usize, cur_type: Option<String>) {
        let src = self.src;
        match node.kind() {
            "function_definition" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let kind = if cur_type.is_some() { "method" } else { "function" };
                let s = self.add(name, kind, node, cur_type.clone());
                self.out.contains.push((container, s));
                if let Some(b) = node.child_by_field_name("body") {
                    // nested defs are not methods of the class
                    self.walk(b, s, s, cur_type.clone());
                }
            }
            "class_definition" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string();
                let s = self.add(&name, "class", node, None);
                self.out.contains.push((container, s));
                if let Some(sup) = node.child_by_field_name("superclasses") {
                    let mut c = sup.walk();
                    for b in sup.named_children(&mut c) {
                        if matches!(b.kind(), "identifier" | "attribute") {
                            self.out.impls.push(RawImpl {
                                src_sym: Some(s),
                                src_type: None,
                                base: last_ident(text(b, src)),
                                file: self.file,
                            });
                        }
                    }
                }
                if let Some(b) = node.child_by_field_name("body") {
                    self.children(b, s, enclosing, Some(name));
                }
            }
            "call" => {
                if let Some(f) = node.child_by_field_name("function") {
                    match f.kind() {
                        "identifier" => self.call(enclosing, text(f, src).to_string(), None, &cur_type),
                        "attribute" => {
                            let name = f.child_by_field_name("attribute").map(|n| text(n, src)).unwrap_or("").to_string();
                            let obj = f.child_by_field_name("object").map(|n| text(n, src).to_string());
                            self.call(enclosing, name, obj, &cur_type);
                        }
                        _ => {}
                    }
                }
                self.children(node, container, enclosing, cur_type);
            }
            "import_statement" => {
                let mut c = node.walk();
                let kids: Vec<Node> = node.named_children(&mut c).collect();
                for k in kids {
                    match k.kind() {
                        "dotted_name" => {
                            let m = text(k, src).to_string();
                            self.out.files[self.file].imports.modules.push((m.clone(), m.clone()));
                            self.out.files[self.file].imports.specs.push(m);
                        }
                        "aliased_import" => {
                            let m = k.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string();
                            let a = k.child_by_field_name("alias").map(|n| text(n, src)).unwrap_or("").to_string();
                            self.out.files[self.file].imports.modules.push((a, m.clone()));
                            self.out.files[self.file].imports.specs.push(m);
                        }
                        _ => {}
                    }
                }
            }
            "import_from_statement" => {
                let module = node.child_by_field_name("module_name").map(|n| text(n, src).to_string()).unwrap_or_default();
                self.out.files[self.file].imports.specs.push(module.clone());
                let mut c = node.walk();
                let kids: Vec<Node> = node.children_by_field_name("name", &mut c).collect();
                for k in kids {
                    let (orig, local) = match k.kind() {
                        "aliased_import" => (
                            k.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string(),
                            k.child_by_field_name("alias").map(|n| text(n, src)).unwrap_or("").to_string(),
                        ),
                        _ => (text(k, src).to_string(), text(k, src).to_string()),
                    };
                    self.out.files[self.file].imports.names.push((local, module.clone(), orig));
                }
            }
            _ => self.children(node, container, enclosing, cur_type),
        }
    }

    // ---------------- Go ----------------
    fn go(&mut self, node: Node, container: usize, enclosing: usize, cur_type: Option<String>) {
        let src = self.src;
        match node.kind() {
            "function_declaration" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let s = self.add(name, "function", node, None);
                self.out.contains.push((container, s));
                if let Some(b) = node.child_by_field_name("body") {
                    self.walk(b, s, s, None);
                }
            }
            "method_declaration" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let recv = node
                    .child_by_field_name("receiver")
                    .and_then(|r| {
                        let mut c = r.walk();
                        let p = r.named_children(&mut c).next();
                        p
                    })
                    .and_then(|p| p.child_by_field_name("type"))
                    .map(|t| last_ident(text(t, src).trim_start_matches('*')))
                    .map(|t| t.split('[').next().unwrap_or("").to_string());
                let s = self.add(name, "method", node, recv.clone());
                if let Some(r) = recv.clone() {
                    self.out.contains_by_type.push((s, r));
                } else {
                    self.out.contains.push((container, s));
                }
                if let Some(b) = node.child_by_field_name("body") {
                    self.walk(b, s, s, recv);
                }
            }
            "type_spec" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let kind = match node.child_by_field_name("type").map(|t| t.kind()) {
                    Some("struct_type") => "struct",
                    Some("interface_type") => "interface",
                    _ => "type",
                };
                let s = self.add(name, kind, node, None);
                self.out.contains.push((container, s));
            }
            "import_spec" => {
                let path = node
                    .child_by_field_name("path")
                    .map(|n| text(n, src).trim_matches('"').to_string())
                    .unwrap_or_default();
                let alias = node.child_by_field_name("name").map(|n| text(n, src).to_string());
                let default_alias = {
                    let segs: Vec<&str> = path.split('/').collect();
                    let last = segs.last().copied().unwrap_or("");
                    if last.len() >= 2 && last.starts_with('v') && last[1..].chars().all(|c| c.is_ascii_digit()) && segs.len() > 1 {
                        segs[segs.len() - 2].to_string()
                    } else {
                        last.to_string()
                    }
                };
                let a = alias.unwrap_or(default_alias);
                if a != "_" && a != "." {
                    self.out.files[self.file].imports.modules.push((a, path.clone()));
                }
                self.out.files[self.file].imports.specs.push(path);
            }
            "call_expression" => {
                if let Some(f) = node.child_by_field_name("function") {
                    match f.kind() {
                        "identifier" => self.call(enclosing, text(f, src).to_string(), None, &cur_type),
                        "selector_expression" => {
                            let name = f.child_by_field_name("field").map(|n| text(n, src)).unwrap_or("").to_string();
                            let op = f.child_by_field_name("operand").map(|n| text(n, src).to_string());
                            self.call(enclosing, name, op, &cur_type);
                        }
                        _ => {}
                    }
                }
                self.children(node, container, enclosing, cur_type);
            }
            "composite_literal" => {
                if let Some(t) = node.child_by_field_name("type") {
                    let raw = text(t, src);
                    if let Some((q, n)) = raw.split_once('.') {
                        self.call(enclosing, n.to_string(), Some(q.to_string()), &cur_type);
                    } else {
                        self.call(enclosing, raw.split('[').next().unwrap_or("").to_string(), None, &cur_type);
                    }
                }
                self.children(node, container, enclosing, cur_type);
            }
            _ => self.children(node, container, enclosing, cur_type),
        }
    }

    // ---------------- TS / JS ----------------
    fn js(&mut self, node: Node, container: usize, enclosing: usize, cur_type: Option<String>) {
        let src = self.src;
        match node.kind() {
            "function_declaration" | "generator_function_declaration" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let s = self.add(name, "function", node, None);
                self.out.contains.push((container, s));
                if let Some(b) = node.child_by_field_name("body") {
                    self.walk(b, s, s, None);
                }
            }
            "class_declaration" | "abstract_class_declaration" | "class" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string();
                if name.is_empty() {
                    return self.children(node, container, enclosing, cur_type);
                }
                let s = self.add(&name, "class", node, None);
                self.out.contains.push((container, s));
                let mut c = node.walk();
                let kids: Vec<Node> = node.named_children(&mut c).collect();
                for k in kids {
                    if k.kind() == "class_heritage" {
                        let mut stack = vec![k];
                        while let Some(h) = stack.pop() {
                            let mut c2 = h.walk();
                            for ch in h.named_children(&mut c2) {
                                match ch.kind() {
                                    "identifier" | "type_identifier" | "member_expression" | "nested_type_identifier" => {
                                        self.out.impls.push(RawImpl {
                                            src_sym: Some(s),
                                            src_type: None,
                                            base: last_ident(text(ch, src)),
                                            file: self.file,
                                        });
                                    }
                                    "generic_type" => {
                                        if let Some(n) = ch.child_by_field_name("name") {
                                            self.out.impls.push(RawImpl {
                                                src_sym: Some(s),
                                                src_type: None,
                                                base: last_ident(text(n, src)),
                                                file: self.file,
                                            });
                                        }
                                    }
                                    _ => stack.push(ch),
                                }
                            }
                        }
                    }
                }
                if let Some(b) = node.child_by_field_name("body") {
                    self.children(b, s, s, Some(name));
                }
            }
            "method_definition" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let s = self.add(name, "method", node, cur_type.clone());
                self.out.contains.push((container, s));
                if let Some(b) = node.child_by_field_name("body") {
                    self.walk(b, s, s, cur_type);
                }
            }
            "interface_declaration" | "type_alias_declaration" | "enum_declaration" => {
                let name = node.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("");
                let kind = match node.kind() {
                    "interface_declaration" => "interface",
                    "enum_declaration" => "enum",
                    _ => "type",
                };
                let s = self.add(name, kind, node, None);
                self.out.contains.push((container, s));
            }
            "variable_declarator" => {
                let name_node = node.child_by_field_name("name");
                let val = node.child_by_field_name("value");
                let is_fn = val
                    .map(|v| matches!(v.kind(), "arrow_function" | "function_expression" | "function" | "generator_function"))
                    .unwrap_or(false);
                // React components wrapped in memo()/forwardRef() also count
                let wrapped_fn = val
                    .filter(|v| v.kind() == "call_expression")
                    .and_then(|v| v.child_by_field_name("arguments"))
                    .map(|a| {
                        let mut c = a.walk();
                        let r = a
                            .named_children(&mut c)
                            .any(|x| matches!(x.kind(), "arrow_function" | "function_expression" | "function"));
                        r
                    })
                    .unwrap_or(false);
                match (name_node, is_fn || wrapped_fn) {
                    (Some(n), true) if n.kind() == "identifier" => {
                        let s = self.add(text(n, src), "function", node, None);
                        self.out.contains.push((container, s));
                        if let Some(v) = val {
                            self.walk(v, s, s, None);
                        }
                    }
                    _ => self.children(node, container, enclosing, cur_type),
                }
            }
            "call_expression" => {
                if let Some(f) = node.child_by_field_name("function") {
                    match f.kind() {
                        "identifier" => self.call(enclosing, text(f, src).to_string(), None, &cur_type),
                        "member_expression" => {
                            let name = f.child_by_field_name("property").map(|n| text(n, src)).unwrap_or("").to_string();
                            let obj = f.child_by_field_name("object").map(|n| text(n, src).to_string());
                            self.call(enclosing, name, obj, &cur_type);
                        }
                        _ => {}
                    }
                }
                self.children(node, container, enclosing, cur_type);
            }
            "new_expression" => {
                if let Some(c) = node.child_by_field_name("constructor") {
                    self.call(enclosing, last_ident(text(c, src)), None, &cur_type);
                }
                self.children(node, container, enclosing, cur_type);
            }
            "jsx_opening_element" | "jsx_self_closing_element" => {
                if let Some(n) = node.child_by_field_name("name") {
                    let raw = text(n, src);
                    let starts_upper = raw.chars().next().map(|c| c.is_ascii_uppercase()).unwrap_or(false);
                    if starts_upper {
                        if let Some((q, nm)) = raw.rsplit_once('.') {
                            self.call(enclosing, nm.to_string(), Some(q.to_string()), &cur_type);
                        } else {
                            self.call(enclosing, raw.to_string(), None, &cur_type);
                        }
                    }
                }
                self.children(node, container, enclosing, cur_type);
            }
            "import_statement" => {
                let spec = node
                    .child_by_field_name("source")
                    .map(|n| text(n, src).trim_matches(|c| c == '"' || c == '\'' || c == '`').to_string())
                    .unwrap_or_default();
                self.out.files[self.file].imports.specs.push(spec.clone());
                let mut c = node.walk();
                let kids: Vec<Node> = node.named_children(&mut c).collect();
                for k in kids {
                    if k.kind() != "import_clause" {
                        continue;
                    }
                    let mut c2 = k.walk();
                    let parts: Vec<Node> = k.named_children(&mut c2).collect();
                    for p in parts {
                        match p.kind() {
                            "identifier" => {
                                let l = text(p, src).to_string();
                                self.out.files[self.file].imports.names.push((l.clone(), spec.clone(), "default".into()));
                            }
                            "namespace_import" => {
                                let mut c3 = p.walk();
                                let id = p.named_children(&mut c3).find(|x| x.kind() == "identifier");
                                if let Some(id) = id {
                                    self.out.files[self.file].imports.modules.push((text(id, src).to_string(), spec.clone()));
                                }
                            }
                            "named_imports" => {
                                let mut c3 = p.walk();
                                let specs: Vec<Node> = p.named_children(&mut c3).collect();
                                for s in specs {
                                    if s.kind() != "import_specifier" {
                                        continue;
                                    }
                                    let orig = s.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string();
                                    let local = s
                                        .child_by_field_name("alias")
                                        .map(|n| text(n, src).to_string())
                                        .unwrap_or_else(|| orig.clone());
                                    self.out.files[self.file].imports.names.push((local, spec.clone(), orig));
                                }
                            }
                            _ => {}
                        }
                    }
                }
            }
            _ => self.children(node, container, enclosing, cur_type),
        }
    }
}

fn rust_callee(f: Node, src: &[u8]) -> (String, Option<String>) {
    match f.kind() {
        "identifier" => (text(f, src).to_string(), None),
        "scoped_identifier" => {
            let name = f.child_by_field_name("name").map(|n| text(n, src)).unwrap_or("").to_string();
            let path = f.child_by_field_name("path").map(|n| text(n, src).to_string());
            (name, path)
        }
        "field_expression" => {
            let name = f.child_by_field_name("field").map(|n| text(n, src)).unwrap_or("").to_string();
            let obj = f.child_by_field_name("value").map(|n| text(n, src).to_string());
            (name, obj)
        }
        "generic_function" => match f.child_by_field_name("function") {
            Some(inner) => rust_callee(inner, src),
            None => (String::new(), None),
        },
        _ => (String::new(), None),
    }
}

fn collect_rust_use(n: Node, src: &[u8], out: &mut Vec<(String, String)>) {
    match n.kind() {
        "identifier" | "type_identifier" => {
            let s = text(n, src).to_string();
            out.push((s.clone(), s));
        }
        "scoped_identifier" => {
            if let Some(name) = n.child_by_field_name("name") {
                let s = text(name, src).to_string();
                out.push((s.clone(), s));
            }
        }
        "use_as_clause" => {
            let orig = n.child_by_field_name("path").map(|p| last_ident(text(p, src))).unwrap_or_default();
            let alias = n.child_by_field_name("alias").map(|a| text(a, src).to_string()).unwrap_or_default();
            out.push((alias, orig));
        }
        "scoped_use_list" => {
            if let Some(list) = n.child_by_field_name("list") {
                collect_rust_use(list, src, out);
            }
        }
        "use_list" => {
            let mut c = n.walk();
            for k in n.named_children(&mut c) {
                collect_rust_use(k, src, out);
            }
        }
        _ => {}
    }
}

pub fn extract_repo(root: &Path, skip_dirs: &[&str]) -> anyhow::Result<Extracted> {
    let mut out = Extracted::default();
    let mut paths: Vec<String> = Vec::new();
    let it = walkdir::WalkDir::new(root).sort_by_file_name().into_iter().filter_entry(|e| {
        let name = e.file_name().to_string_lossy();
        if e.depth() == 0 {
            return true;
        }
        if e.file_type().is_dir() {
            return !(name.starts_with('.') || skip_dirs.contains(&name.as_ref()));
        }
        true
    });
    for e in it {
        let e = e?;
        if !e.file_type().is_file() {
            continue;
        }
        let rel = e.path().strip_prefix(root)?.to_string_lossy().to_string();
        let fname = e.file_name().to_string_lossy();
        if fname.ends_with(".pb.go")
            || fname.contains("_generated.")
            || fname.ends_with(".d.ts")
            || fname.ends_with(".min.js")
            || fname.ends_with("_pb2.py")
            || fname.ends_with("_pb2_grpc.py")
        {
            continue;
        }
        if Lang::from_path(&rel).is_none() {
            continue;
        }
        if e.metadata().map(|m| m.len() > 1_000_000).unwrap_or(true) {
            continue;
        }
        paths.push(rel);
    }

    let mut parsers: HashMap<&'static str, Parser> = HashMap::new();
    for rel in paths {
        let lang = Lang::from_path(&rel).unwrap();
        let src = match std::fs::read(root.join(&rel)) {
            Ok(b) => b,
            Err(_) => continue,
        };
        if is_generated(&src) {
            out.generated_skipped += 1;
            continue;
        }
        let key: &'static str = match lang {
            Lang::Rust => "rust",
            Lang::Py => "py",
            Lang::Ts => "ts",
            Lang::Tsx => "tsx",
            Lang::Js => "js",
            Lang::Go => "go",
        };
        let parser = parsers.entry(key).or_insert_with(|| {
            let mut p = Parser::new();
            let l: tree_sitter::Language = match lang {
                Lang::Rust => tree_sitter_rust::LANGUAGE.into(),
                Lang::Py => tree_sitter_python::LANGUAGE.into(),
                Lang::Ts => tree_sitter_typescript::LANGUAGE_TYPESCRIPT.into(),
                Lang::Tsx => tree_sitter_typescript::LANGUAGE_TSX.into(),
                Lang::Js => tree_sitter_javascript::LANGUAGE.into(),
                Lang::Go => tree_sitter_go::LANGUAGE.into(),
            };
            p.set_language(&l).expect("grammar");
            p
        });
        let tree = match parser.parse(&src, None) {
            Some(t) => t,
            None => {
                out.parse_errors += 1;
                continue;
            }
        };
        if tree.root_node().has_error() {
            out.parse_errors += 1;
        }
        let file = out.files.len();
        let module_sym = out.syms.len();
        out.syms.push(Sym {
            name: rel.clone(),
            kind: "module",
            parent_type: None,
            file,
            line: 1,
        });
        out.files.push(FileRec {
            path: rel,
            lang,
            module_sym,
            imports: RawImports::default(),
        });
        let mut w = Walker {
            src: &src,
            file,
            lang,
            out: &mut out,
        };
        w.walk(tree.root_node(), module_sym, module_sym, None);
    }
    Ok(out)
}
