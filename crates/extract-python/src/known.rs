pub fn is_stdlib_top(module: &str) -> bool {
    STDLIB.binary_search(&module).is_ok()
}

pub fn is_builtin(name: &str) -> bool {
    BUILTINS.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_for_binary_search() {
        assert!(STDLIB.windows(2).all(|w| w[0] < w[1]));
        assert!(BUILTINS.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn lookups() {
        assert!(is_stdlib_top("os"));
        assert!(is_stdlib_top("__future__"));
        assert!(!is_stdlib_top("requests"));
        assert!(is_builtin("print"));
        assert!(!is_builtin("printf"));
    }
}
